_SECTION_PARAMS: dict[str, list[ParamSpec]] = _build_lookup()


def get_section_params(section_name: str) -> list[ParamSpec]:
    """Return the list of ParamSpec for a given section, or empty list if unknown."""
    return _SECTION_PARAMS.get(section_name, [])


def get_param_spec(section_name: str, param_name: str) -> ParamSpec | None:
    """Look up a ParamSpec by section and parameter name."""
    for ps in get_section_params(section_name):
        if ps.name == param_name:
            return ps
    return None


def is_known_param(section_name: str, param_name: str) -> bool:
    """Check whether a parameter name is known for the given section."""
    return get_param_spec(section_name, param_name) is not None
