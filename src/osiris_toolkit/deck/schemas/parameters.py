"""Per-parameter schema definitions for all OSIRIS input deck sections.

Each parameter is defined by its Fortran type, Python type, dimensions, default value,
constraints, and description -- sourced from the Fortran namelist definitions in the
OSIRIS source code.
"""

from dataclasses import dataclass
from typing import Any


@dataclass(frozen=True)
class ParamSpec:
    """Specification for a single parameter within an OSIRIS section.

    Derived from the corresponding Fortran namelist declaration and
    default-value/validation logic in the section's read_input subroutine.
    """

    name: str
    fortran_type: str  # e.g. "real(p_double)", "integer", "logical", "character(len=20)"
    python_type: type  # float, int, bool, str
    dimensions: tuple[int | str, ...] | None = None
    # None  -> scalar
    # ()    -> scalar (explicit)
    # (3,)  -> 1D array with 3 elements
    # ("p_x_dim",) -> size depends on compile-time dimension
    # (2, "p_x_dim") -> 2D: 2 walls x spatial dimensions
    default: Any = None
    required: bool = False  # Fortran namelist: individual params always have defaults
    constraints: list[str] | None = None  # e.g. ["> 0", "in (cartesian, cylindrical)"]
    condition: str | None = None  # e.g. "if_move == 1" or "__HAS_SPIN__"
    description: str = ""


